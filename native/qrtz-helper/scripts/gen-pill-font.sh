#!/bin/bash
# Regenerates Sources/QrtzEcho/PillFont.swift from the renderer's bundled font, so the native echo pill draws
# with the same file (Core Text reads WOFF2 directly). PillTests fails if the two drift apart.
set -euo pipefail
cd "$(dirname "$0")/.."
SRC=../../packages/ui/src/fonts/AlloVariable.woff2
{
  echo "// Generated by scripts/gen-pill-font.sh from packages/ui/src/fonts/AlloVariable.woff2 (Allo 1.0.3 by Josh Puckett,"
  echo "// OFL-1.1: packages/ui/src/fonts/OFL-Allo.txt). Do not edit."
  echo "import Foundation"
  echo ""
  echo "public enum PillFont {"
  echo "    public static let family = \"Allo Variable\""
  echo "    /// PostScript name of the variable font's default instance (wght 400): unambiguous for NSFont(name:)."
  echo "    public static let postScriptName = \"AlloVariable-Regular\""
  echo "    public static var woff2: Data { Data(base64Encoded: base64)! }"
  printf '    static let base64 = "%s"\n' "$(base64 < "$SRC" | tr -d '\n')"
  echo "}"
} > Sources/QrtzEcho/PillFont.swift
